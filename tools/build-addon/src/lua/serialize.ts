/**
 * Serializes plain data (strings, numbers, booleans, arrays, objects) into a readable Lua table literal.
 * Accepts `unknown` so typed interfaces can be passed directly; anything else (functions, symbols) is rejected.
 */

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;
const INTEGER = /^\d+$/;
const INDENT = "  ";

/** Characters the game's default fonts can't draw, replaced with ones they can. */
const GAME_TEXT: Readonly<Record<string, string>> = {
  "→": "->",
  "←": "<-",
  "≤": "<=",
  "≥": ">=",
  "−": "-",
  "≈": "~",
  "★": "*",
};
const UNDRAWABLE = new RegExp(`[${Object.keys(GAME_TEXT).join("")}]`, "g");

export const gameText = (value: string): string => value.replace(UNDRAWABLE, (ch) => GAME_TEXT[ch] ?? ch);

/** A Lua string literal. `|` is doubled because the WoW client treats a single `|` as an escape code in text. */
export function luaString(value: string): string {
  const escaped = gameText(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ").replace(/\|/g, "||");
  return `"${escaped}"`;
}

function luaKey(key: string): string {
  if (IDENTIFIER.test(key)) return key;
  if (INTEGER.test(key)) return `[${key}]`;
  return `[${luaString(key)}]`;
}

function isScalar(value: unknown): boolean {
  return value === null || value === undefined || typeof value !== "object";
}

export function toLua(value: unknown, indent = ""): string {
  if (value === null || value === undefined) return "nil";
  if (typeof value === "boolean") return String(value);
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new TypeError(`Cannot write ${value} to Lua`);
    return String(value);
  }
  if (typeof value === "string") return luaString(value);
  if (typeof value !== "object") throw new TypeError(`Cannot write a ${typeof value} to Lua`);

  const inner = indent + INDENT;
  if (Array.isArray(value)) {
    if (value.length === 0) return "{}";
    if (value.every(isScalar)) return `{ ${value.map((v) => toLua(v)).join(", ")} }`;
    return `{\n${value.map((v) => `${inner}${toLua(v, inner)},`).join("\n")}\n${indent}}`;
  }

  const entries = Object.entries(value).filter(([, v]) => v !== undefined && v !== null);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([k, v]) => `${inner}${luaKey(k)} = ${toLua(v, inner)},`).join("\n")}\n${indent}}`;
}

/** A complete data file: every entry becomes `ns.data.<name> = <table>`. */
export function luaDataFile(entries: Readonly<Record<string, unknown>>): string {
  const body = Object.entries(entries)
    .map(([name, value]) => `ns.data.${name} = ${toLua(value)}\n`)
    .join("\n");
  return `-- GENERATED by tools/build-addon from @btc/guide-data. Do not edit by hand.\nlocal _, ns = ...\n\n${body}`;
}
