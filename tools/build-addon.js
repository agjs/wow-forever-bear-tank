// Builds addon/BearTankQuests/Data.lua from dquests.js and zips the addon to BearTankQuests.zip.
// Run from the repo root: node tools/build-addon.js
const fs = require("fs"), vm = require("vm"), path = require("path"), { execSync } = require("child_process");
const root = path.join(__dirname, "..");
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "dquests.js"), "utf8"), ctx);
const D = ctx.window.DQUESTS;

const lua = s => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ").replace(/\|/g, "||") + '"';
const inside = w => /^(inside|drops|a random drop)/i.test(w);
const place = w => w.replace(/\s*\([^)]*\)\s*$/, "").replace(/, walks around$/, "");
const coords = w => (w.match(/\(([\d.]+),\s*([\d.]+)\)/) || []).slice(1).map(Number);
const zoneOf = w => { const p = place(w).split(",").map(x => x.trim()); return p[p.length - 1]; };

let out = "-- Generated by tools/build-addon.js from the Bear Tank Codex site data. Do not edit by hand.\nlocal _, ns = ...\nns.DUNGEONS = {\n";
for (const d of D) {
  const stops = [];
  d.q.forEach(x => {
    const w = x[6], k = inside(w) ? "__in" : place(w);
    let g = stops.find(s => s.k === k);
    if (!g) { const c = coords(w); stops.push(g = { k, title: k === "__in" ? "Inside " + d.name : place(w), zone: k === "__in" ? "" : zoneOf(w), x: c[0], y: c[1], inside: k === "__in", q: [] }); }
    g.q.push(x);
  });
  stops.sort((a, b) => a.inside - b.inside);
  out += `  { key = ${lua(d.key)}, name = ${lua(d.name)}, lo = ${d.lv[0]}, hi = ${d.lv[1]}, stops = {\n`;
  for (const s of stops) {
    out += `    { title = ${lua(s.title)}, zone = ${lua(s.zone)}, x = ${s.x ?? "nil"}, y = ${s.y ?? "nil"}, inside = ${s.inside}, q = {\n`;
    for (const [id, n, side, req, , giver, where, note] of s.q)
      out += `      { id = ${id}, name = ${lua(n)}, horde = ${side === "H"}, req = ${req}, giver = ${lua(giver)}, where = ${lua(s.inside ? where : "")}, note = ${lua(note || "")} },\n`;
    out += "    } },\n";
  }
  out += "  } },\n";
}
out += "}\n";
fs.writeFileSync(path.join(root, "addon/BearTankQuests/Data.lua"), out);
execSync("rm -f BearTankQuests.zip && cd addon && zip -qr ../BearTankQuests.zip BearTankQuests -x '*.DS_Store'", { cwd: root });
console.log("Data.lua:", D.length, "dungeons,", D.reduce((n, d) => n + d.q.length, 0), "quests; zip written");
